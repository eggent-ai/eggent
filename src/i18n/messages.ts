export type MessageKey = keyof typeof enMessages;

export const messages: Record<SupportedLocale, MessageDictionary> = {
  en: enMessages,
};

export type MessageValues = Record<string, string | number | boolean | null | undefined>;

export function translate(locale: SupportedLocale, key: MessageKey, values?: MessageValues): string {
  const template = messages[locale]?.[key] || messages.en[key] || key;
  if (!values) return template;
  return template.replace(/\{([A-Za-z0-9_]+)\}/g, (match, name: string) => {
    const value = values[name];
    return value === undefined || value === null ? match : String(value);
  });
}
